"""Tests for SNI parser."""

import asyncio
import ssl

import pytest

from snitun.exceptions import ParseSNIError, ParseSNIIncompleteError
from snitun.server import sni

from . import const_tls as raw


@pytest.mark.parametrize(
    "test_package",
    [
        raw.TLS_1_0,
        raw.TLS_1_0_OLD,
        raw.TLS_1_2,
        raw.TLS_1_2_MORE,
        raw.TLS_1_2_ORDER,
        raw.TLS_1_2_BAD,
    ],
)
def test_good_client_hello(test_package: bytes) -> None:
    """Test good TLS packages."""
    assert sni.parse_tls_sni(test_package) == "localhost"


@pytest.mark.parametrize(
    "test_package",
    [raw.BAD_DATA1, raw.BAD_DATA2, raw.SSL_2_0, raw.SSL_3_0],
)
def test_bad_client_hello(test_package: bytes) -> None:
    """Test bad client hello."""
    with pytest.raises(ParseSNIError):
        sni.parse_tls_sni(test_package)


@pytest.mark.parametrize(
    ("offset", "width", "length"),
    [
        pytest.param(3, 2, 0, id="empty-record"),
        pytest.param(3, 2, 3, id="short-handshake-header"),
        pytest.param(3, 2, 71, id="hello-exceeds-record"),
        pytest.param(6, 3, 0, id="empty-hello"),
        pytest.param(6, 3, 34, id="missing-session-id-length"),
        pytest.param(6, 3, 35, id="missing-cipher-suites-length"),
        pytest.param(6, 3, 41, id="missing-compression-length"),
        pytest.param(6, 3, 43, id="missing-extensions-length"),
        pytest.param(6, 3, 67, id="extensions-exceed-hello"),
        pytest.param(6, 3, 69, id="hello-exceeds-record-length"),
        pytest.param(52, 2, 0, id="empty-extensions-with-trailing-sni"),
        pytest.param(52, 2, 17, id="sni-exceeds-extensions"),
        pytest.param(52, 2, 24, id="extensions-exceed-record"),
        pytest.param(56, 2, 0, id="empty-sni-extension"),
        pytest.param(56, 2, 1, id="short-server-name-list-length"),
        pytest.param(56, 2, 13, id="list-exceeds-sni-extension"),
        pytest.param(56, 2, 24, id="sni-exceeds-record"),
        pytest.param(58, 2, 0, id="empty-server-name-list"),
        pytest.param(58, 2, 11, id="hostname-exceeds-list"),
        pytest.param(58, 2, 13, id="list-exceeds-extension"),
        pytest.param(61, 2, 0, id="empty-hostname"),
        pytest.param(61, 2, 10, id="hostname-includes-next-extension"),
        pytest.param(61, 2, 65535, id="hostname-exceeds-buffer"),
    ],
)
def test_invalid_client_hello_lengths(offset: int, width: int, length: int) -> None:
    """Reject invalid lengths even when the backing buffer contains more bytes."""
    # Offsets refer to the annotated TLS_1_2 fixture in const_tls.py.
    data = bytearray(raw.TLS_1_2)
    data[offset : offset + width] = length.to_bytes(width, "big")

    with pytest.raises(ParseSNIError):
        sni.parse_tls_sni(bytes(data))


@pytest.mark.parametrize("length", range(len(raw.TLS_1_2)))
def test_truncated_client_hello(length: int) -> None:
    """Every truncated prefix raises a parser error rather than IndexError."""
    with pytest.raises(ParseSNIError):
        sni.parse_tls_sni(raw.TLS_1_2[:length])


def test_incomplete_tls_record() -> None:
    """A partial record can still be completed by the streaming caller."""
    with pytest.raises(ParseSNIIncompleteError):
        sni.parse_tls_sni(raw.TLS_1_2[:-1])


def test_client_hello_with_following_record() -> None:
    """Bytes from a following TLS record do not affect SNI parsing."""
    assert sni.parse_tls_sni(raw.TLS_1_2 + b"\x14\x03\x03\x00\x01\x01") == "localhost"


@pytest.mark.parametrize("version", [ssl.TLSVersion.TLSv1_2, ssl.TLSVersion.TLSv1_3])
def test_openssl_client_hello(version: ssl.TLSVersion) -> None:
    """Accept actual TLS 1.2 and 1.3 ClientHello records generated by OpenSSL."""
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.minimum_version = context.maximum_version = version
    incoming = ssl.MemoryBIO()
    outgoing = ssl.MemoryBIO()
    client = context.wrap_bio(incoming, outgoing, server_hostname="localhost")

    with pytest.raises(ssl.SSLWantReadError):
        client.do_handshake()

    assert sni.parse_tls_sni(outgoing.read()) == "localhost"


class _ChunkReader:
    """Minimal async reader that yields pre-set chunks, then EOF."""

    def __init__(self, *chunks: bytes) -> None:
        self._chunks = list(chunks)

    async def read(self, _n: int = -1) -> bytes:
        return self._chunks.pop(0) if self._chunks else b""


async def test_payload_reader_good() -> None:
    """A complete ClientHello is returned intact."""
    reader = asyncio.StreamReader()
    reader.feed_data(raw.TLS_1_2)
    reader.feed_eof()

    assert await sni.payload_reader(reader) == raw.TLS_1_2


async def test_payload_reader_completes_across_reads() -> None:
    """A record split across multiple reads is reassembled."""
    reader = _ChunkReader(raw.TLS_1_2[:6], raw.TLS_1_2[6:])

    assert await sni.payload_reader(reader) == raw.TLS_1_2  # type: ignore[arg-type]


async def test_payload_reader_short_record_header() -> None:
    """A stream shorter than the 6-byte record header returns None (no OOB)."""
    reader = asyncio.StreamReader()
    # Exactly 5 bytes starting with the handshake content type: the old code
    # indexed data[5] here and raised IndexError.
    reader.feed_data(b"\x16\x03\x01\x00\x05")
    reader.feed_eof()

    assert await sni.payload_reader(reader) is None


async def test_payload_reader_eof_mid_record() -> None:
    """EOF before the full TLS record arrives returns None (no busy-spin)."""
    reader = asyncio.StreamReader()
    # Valid 6-byte prefix declaring a large record, then EOF.
    reader.feed_data(b"\x16\x03\x01\xff\xff\x01")
    reader.feed_eof()

    assert await sni.payload_reader(reader) is None


async def test_payload_reader_not_handshake() -> None:
    """Non-handshake content type returns None."""
    reader = asyncio.StreamReader()
    reader.feed_data(b"\x17\x03\x01\x00\x01\x01")
    reader.feed_eof()

    assert await sni.payload_reader(reader) is None
